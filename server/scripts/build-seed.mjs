import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {normalizeBody} from '../src/crypto.mjs';

const root=new URL('../',import.meta.url);
const files={'01-short.txt':'کوتاه','02-together.txt':'صمیمی','03-gratitude.txt':'قدردانی','04-longing.txt':'دلتنگی','05-care.txt':'صمیمی'};
const hash=text=>createHash('sha256').update(text).digest('hex');
function stableId(fingerprint){
 const bytes=createHash('sha1').update('delneveshte-catalog-v1:'+fingerprint).digest().subarray(0,16);
 bytes[6]=(bytes[6]&15)|80;bytes[8]=(bytes[8]&63)|128;
 const hex=bytes.toString('hex');return `${hex.slice(0,8)}-${hex.slice(8,12)}-${hex.slice(12,16)}-${hex.slice(16,20)}-${hex.slice(20)}`;
}
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
export function catalog(){
 const unique=new Map();
 for(const [file,category] of Object.entries(files)){
  const lines=readFileSync(new URL('data/initial/'+file,root),'utf8').split(/\r?\n/).map(s=>s.trim()).filter(Boolean);
  for(const [index,body] of lines.entries()){
   if(body.length>2400)throw new Error(`${file}:${index+1}: text too long`);
   if(!/\p{Extended_Pictographic}/u.test(body))throw new Error(`${file}:${index+1}: missing contextual emoji`);
   const fingerprint=hash(normalizeBody(body));
   if(unique.has(fingerprint))throw new Error(`${file}:${index+1}: duplicate text after Unicode/punctuation/emoji normalization`);
   unique.set(fingerprint,{id:stableId(fingerprint),body,fingerprint,category});
  }
 }
 if(unique.size<1000)throw new Error(`At least 1000 unique authored messages are required; found ${unique.size}`);
 return [...unique.values()];
}
export function seedSql(){
 const rows=catalog(),statements=['-- Generated from the reviewed original messages and attributed public-domain verses. Do not edit this file.'];
 for(let i=0;i<rows.length;i+=40){
  const values=rows.slice(i,i+40).map(r=>`(${quote(r.id)},${quote(r.body)},${quote(r.fingerprint)},${quote(r.category)},1,CAST(strftime('%s','now') AS INTEGER)*1000)`);
  statements.push('INSERT OR IGNORE INTO catalog_messages(id,body,fingerprint,category,active,created_at) VALUES\n'+values.join(',\n')+';');
 }
 statements.push(`INSERT OR IGNORE INTO seed_runs(version,count,seeded_at) VALUES('catalog-v1',${rows.length},CAST(strftime('%s','now') AS INTEGER)*1000);`);
 return {count:rows.length,sql:statements.join('\n')+'\n'};
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const result=seedSql();mkdirSync(new URL('migrations/',root),{recursive:true});
 writeFileSync(new URL('migrations/0002_initial_catalog.sql',root),result.sql);
 writeFileSync(new URL('migrations/0006_clean_catalog.sql',root),"DELETE FROM catalog_origins; DELETE FROM catalog_messages; DELETE FROM catalog_jobs; DELETE FROM seed_runs;\n"+result.sql);
 console.log(`Prepared deployment seed job: ${result.count} unique initial messages.`);
}
